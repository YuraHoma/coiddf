(async () => {
  // старі демонстраційні проєкти прибираємо — їх замінює реальний перелік
  for (const f of fs.readdirSync(PROJECTS_DIR)) {
    if (f.endsWith(".md")) fs.unlinkSync(path.join(PROJECTS_DIR, f));
  }

  for (const p of P) {
    const src = path.join(SRC_IMG, `p${p.page}-000.jpg`);
    const imgName = `project-${p.slug}.jpg`;
    await sharp(src)
      .resize(1200, null, { withoutEnlargement: true })
      .jpeg({ quality: 86, mozjpeg: true })
      .toFile(path.join(ASSETS_DIR, imgName));

    const fm = [
      "---",
      `title: "${p.title.replace(/"/g, '\\"')}"`,
      `date: ${p.date}`,
      `image: /assets/${imgName}`,
      `excerpt: "${p.excerpt.replace(/"/g, '\\"')}"`,
      "---",
      "",
      body(p),
    ].join("\n");

    fs.writeFileSync(path.join(PROJECTS_DIR, `${p.date}-${p.slug}.md`), fm);
    console.log(`✓ ${p.date}  ${p.title.slice(0, 58)}`);
  }
  console.log(`\nСтворено проєктів: ${P.length}`);
})();
