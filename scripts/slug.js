// Слаг для URL з українського заголовка.
//
// Pages CMS складає ім'я файлу прямо з заголовка, тож новина «Передали
// генератори…» без цього давала б адресу з кирилицею й пробілами —
// %D0%9F%D0%B5… у кожному посиланні. Транслітерація — за офіційною
// романізацією (постанова КМУ №55 від 27.01.2010).
//
// Для вже латинських імен функція — тотожність (лише нижній регістр),
// тому адреси наявних сторінок не змінюються.

const MAP = {
  а: "a", б: "b", в: "v", г: "h", ґ: "g", д: "d", е: "e", є: "ie",
  ж: "zh", з: "z", и: "y", і: "i", ї: "i", й: "i", к: "k", л: "l",
  м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u",
  ф: "f", х: "kh", ц: "ts", ч: "ch", ш: "sh", щ: "shch", ь: "",
  ю: "iu", я: "ia", "’": "", "'": "", "ʼ": "",
};

function ukSlug(text) {
  return String(text)
    .toLowerCase()
    .split("")
    .map((ch) => (ch in MAP ? MAP[ch] : ch))
    .join("")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

module.exports = { ukSlug };
